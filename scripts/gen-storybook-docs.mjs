#!/usr/bin/env node
/**
 * Generate the Storybook docs surface from `docs/storybook-taxonomy.json`.
 *
 * The old Introduction.mdx advertised four sections (Forms, Feedback,
 * Navigation, Data display) that no story had ever used — the docs and the
 * sidebar drifted apart because nothing tied them together. This script is
 * that tie: the taxonomy is authored once, and every section landing page
 * plus the Introduction's section table is derived from it.
 *
 * Writes
 *   .storybook/sections/<Root>-<Section>.mdx   one landing page per section,
 *                                              fully generated (do not edit)
 *   .storybook/Introduction.mdx                the block between the
 *                                              taxonomy:start/end markers
 *
 * Run via `make storybook-docs`. `storybook-lint` fails if the output is
 * stale, so a taxonomy edit cannot land without regenerating.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const STORYBOOK = path.join(ROOT, '.storybook');
const SECTIONS_DIR = path.join(STORYBOOK, 'sections');
const TAXONOMY = JSON.parse(
  fs.readFileSync(path.join(ROOT, 'docs', 'storybook-taxonomy.json'), 'utf8'),
);

const CHECK = process.argv.includes('--check');

/** Mirrors storybook-lint.mjs — keep the two in step. */
const DISPLAY_OVERRIDES = {
  'input-otp': 'Input OTP',
  shell: 'App Shell',
  topbar: 'Topbar',
  ErrorBoundary: 'Error Boundary',
  AuthGuard: 'Auth Guard',
  LoginPage: 'Login',
  ProjectsPage: 'Projects',
};

const displayName = (base) =>
  DISPLAY_OVERRIDES[base] ??
  base
    .split('-')
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ');

/** Storybook's story-id slug, so generated deep links actually resolve. */
const slug = (title) =>
  title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

export function sectionFileName(root, section) {
  return `${slug(root)}-${slug(section)}.mdx`;
}

/* -------------------------------------------------------------------------- */
/*                            section landing pages                           */
/* -------------------------------------------------------------------------- */

function sectionPage(root, section, cfg) {
  const rows = cfg.members
    .map((member) => {
      const name = displayName(member);
      const title = `${root}/${section}/${name}`;
      return `| [${name}](?path=/docs/${slug(title)}--docs) | \`${member}.tsx\` |`;
    })
    .join('\n');

  return `import { Meta } from '@storybook/addon-docs/blocks';

{/* GENERATED by scripts/gen-storybook-docs.mjs from docs/storybook-taxonomy.json — do not edit. */}

<Meta title="${root}/${section}/Overview" />

# ${root} / ${section}

${cfg.blurb}

| Component | Source |
| --- | --- |
${rows}

## House rules

Every component in this section follows the same three rules, and
\`npm run storybook-lint\` fails the build when one breaks:

1. **Tokens only.** No raw hex / rgb / oklch — colour resolves through
   \`var(--token)\`, so editing \`src/App.css\` moves the whole app.
2. **At least three stories.** Default plus the states that actually ship:
   empty, loading, error, disabled — whichever the component really has.
3. **Controls are typed.** Enums get a select, numbers get a slider, events
   land in the Actions panel via \`handlers()\`.

Rendering is gated too: \`npm run storybook-render\` mounts every story in
both themes and fails on an empty canvas, a thrown play function, or
sideways overflow.
`;
}

/* -------------------------------------------------------------------------- */
/*                           Introduction section table                       */
/* -------------------------------------------------------------------------- */

function introBlock() {
  const lines = ['| Section | What lives there |', '| --- | --- |'];
  for (const root of TAXONOMY.order) {
    const cfg = TAXONOMY.roots[root];
    if (!cfg.sections) {
      lines.push(`| **${root}** | ${cfg.blurb} |`);
      continue;
    }
    lines.push(`| **${root}** | ${cfg.blurb} |`);
    for (const [section, sCfg] of Object.entries(cfg.sections)) {
      const link = `?path=/docs/${slug(`${root}/${section}/Overview`)}--docs`;
      lines.push(
        `| [${root} / ${section}](${link}) | ${sCfg.blurb} _(${sCfg.members.length})_ |`,
      );
    }
  }
  return lines.join('\n');
}

/* -------------------------------------------------------------------------- */
/*                                    write                                   */
/* -------------------------------------------------------------------------- */

const START = '{/* taxonomy:start */}';
const END = '{/* taxonomy:end */}';

const wanted = new Map();

for (const [root, cfg] of Object.entries(TAXONOMY.roots)) {
  if (!cfg.sections) continue;
  for (const [section, sCfg] of Object.entries(cfg.sections)) {
    wanted.set(path.join(SECTIONS_DIR, sectionFileName(root, section)), sectionPage(root, section, sCfg));
  }
}

const intro = path.join(STORYBOOK, 'Introduction.mdx');
const introSrc = fs.readFileSync(intro, 'utf8');
if (!introSrc.includes(START) || !introSrc.includes(END)) {
  console.error(
    `gen-storybook-docs: Introduction.mdx is missing the ${START} / ${END} markers.`,
  );
  process.exit(1);
}
const introWanted =
  introSrc.slice(0, introSrc.indexOf(START) + START.length) +
  '\n\n' +
  introBlock() +
  '\n\n' +
  introSrc.slice(introSrc.indexOf(END));
wanted.set(intro, introWanted);

fs.mkdirSync(SECTIONS_DIR, { recursive: true });

// A section removed from the taxonomy must lose its page, or the sidebar keeps
// advertising a group with nothing in it.
const orphans = fs
  .readdirSync(SECTIONS_DIR)
  .map((f) => path.join(SECTIONS_DIR, f))
  .filter((f) => !wanted.has(f));

const stale = [...wanted.entries()].filter(
  ([file, content]) => !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content,
);

if (CHECK) {
  if (stale.length === 0 && orphans.length === 0) {
    console.log(`gen-storybook-docs --check: ${wanted.size} file(s) up to date`);
    process.exit(0);
  }
  console.error('gen-storybook-docs --check: generated docs are stale. Run `make storybook-docs`.');
  for (const [file] of stale) console.error(`  stale:  ${path.relative(ROOT, file)}`);
  for (const file of orphans) console.error(`  orphan: ${path.relative(ROOT, file)}`);
  process.exit(1);
}

for (const [file, content] of wanted) fs.writeFileSync(file, content);
for (const file of orphans) fs.rmSync(file);

console.log(
  `gen-storybook-docs: wrote ${wanted.size} file(s)` +
    (orphans.length ? `, removed ${orphans.length} orphan(s)` : ''),
);
